local HEX = { A = 10, B = 11, C = 12, D = 13, E = 14, F = 15 }

local function digit(ch)
    return HEX[ch] or tonumber(ch)
end

-- Returns { id, name, attack, type, pdef, mdef } (the printed digits) or nil.
function C.get(id)
    local e = C.LIST[id]
    if e == nil then
        return nil
    end

    local code = e[2]
    return
    {
        id     = id,
        name   = e[1],
        attack = digit(code:sub(1, 1)),
        type   = code:sub(2, 2),
        pdef   = digit(code:sub(3, 3)),
        mdef   = digit(code:sub(4, 4)),
        code   = code,
    }
end

return C
